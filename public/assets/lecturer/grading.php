<script>
function markAll(status) {
    document.querySelectorAll('input[type=radio][value="' + status + '"]').forEach(function(r) {
        r.checked = true;
        var tr = r.closest('tr');
        if (tr) tr.dataset.status = status;
    });
    applyAttFilters();
}

function applyAttFilters() {
    var q = (document.getElementById('attSearch')?.value || '').toLowerCase();
    var active = document.querySelector('#attTabs .lec-tab.active')?.dataset.filter || 'all';
    document.querySelectorAll('#attTable tbody tr[data-status]').forEach(function(tr) {
        var okStatus = active === 'all' || tr.dataset.status === active;
        var okSearch = !q || tr.textContent.toLowerCase().indexOf(q) !== -1;
        tr.style.display = (okStatus && okSearch) ? '' : 'none';
    });
}
document.querySelectorAll('#attTabs .lec-tab').forEach(function(tab) {
    tab.addEventListener('click', function() {
        document.querySelectorAll('#attTabs .lec-tab').forEach(function(t) { t.classList.remove('active'); });
        this.classList.add('active');
        applyAttFilters();
    });
});
document.getElementById('attSearch')?.addEventListener('input', applyAttFilters);
document.querySelectorAll('#attTable input[type=radio]').forEach(function(r) {
    r.addEventListener('change', function() {
        this.closest('tr').dataset.status = this.value;
        applyAttFilters();
    });
});
</script>

