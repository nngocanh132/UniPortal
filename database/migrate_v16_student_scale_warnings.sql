-- ============================================================================
-- UniPortal – Migration v16
-- Student-database expansion, performance-warning thresholds and indexes.
--
-- Adds:
--   * Student.is_demo – marks records created by seed scripts so administrators
--     can distinguish generated demo data from real student records.
--   * Configurable thresholds for LowGrade (performance) warnings.
--   * Safe, additive indexes used by student search, attendance risk checks and
--     warning dashboards when the database contains 5,000+ students.
--
-- Idempotent: safe to run repeatedly. Never drops tables/columns and never
-- modifies existing student, enrollment, attendance or grade rows.
--
-- Run:
--   C:/xampp/mysql/bin/mysql.exe -u root uniportal < database/migrate_v16_student_scale_warnings.sql
-- ============================================================================

USE uniportal;
SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- 1. Demo-data marker
-- ---------------------------------------------------------------------------
ALTER TABLE Student
    ADD COLUMN IF NOT EXISTS is_demo TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '1 = generated by a demo seed script, not a real student record';

-- ---------------------------------------------------------------------------
-- 2. Performance (LowGrade) warning thresholds – all configurable
-- ---------------------------------------------------------------------------
INSERT IGNORE INTO SystemConfig (config_key, config_value, description) VALUES
    ('grade_warning_threshold', '5.00',
        'Weighted assessment average (0-10) below this triggers a LowGrade warning'),
    ('grade_component_threshold', '5.00',
        'A single continuous-assessment or midterm component (0-10) below this is flagged'),
    ('grade_decline_delta', '1.00',
        'Drop (0-10 scale) between consecutive assessments that counts as declining performance'),
    ('grade_target_score', '5.50',
        'Target final course score (0-10) used to calculate the score required in remaining assessments'),
    ('assignment_missing_warning', '2',
        'Number of overdue assignments without a submission that triggers a missing-work warning');

-- ---------------------------------------------------------------------------
-- 3. Indexes for large student lists and warning dashboards
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_student_status_year ON Student (status, admission_year);
CREATE INDEX IF NOT EXISTS idx_student_name ON Student (full_name);
CREATE INDEX IF NOT EXISTS idx_student_demo ON Student (is_demo);

CREATE INDEX IF NOT EXISTS idx_enrollment_student_status ON Enrollment (student_id, status);
CREATE INDEX IF NOT EXISTS idx_enrollment_section_status ON Enrollment (section_id, status);

CREATE INDEX IF NOT EXISTS idx_attendance_session_status ON Attendance (session_id, status);
CREATE INDEX IF NOT EXISTS idx_atsection_date_status ON AttendanceSession (section_id, session_date, status);

CREATE INDEX IF NOT EXISTS idx_warning_status_type ON AcademicWarning (status, warning_type);
CREATE INDEX IF NOT EXISTS idx_warning_created ON AcademicWarning (created_at);
CREATE INDEX IF NOT EXISTS idx_tuition_status ON Tuition (status);

CREATE INDEX IF NOT EXISTS idx_grade_enrollment ON Grade (enrollment_id);
CREATE INDEX IF NOT EXISTS idx_submission_enrollment ON Submission (enrollment_id);
